#!/usr/bin/env python3
"""Pack an exported, rigged creature into js/c3d_<name>_mesh.js: pack.py species/NNN-name.json <exported prefix> <rig.json>
Textures are resized to 1024 px WebP and embedded, so the game and the APK need no extra files."""
import json, base64, io, os, sys
from PIL import Image
cfg = json.load(open(sys.argv[1])); m = json.load(open(sys.argv[2] + '.json')); r = json.load(open(sys.argv[3]))
def webp(path, size=1024, q=88):
    b = io.BytesIO(); Image.open(path).convert('RGB').resize((size, size), Image.LANCZOS).save(b, 'WEBP', quality=q, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
a = dict(n=m['n'], lo=m['lo'], hi=m['hi'], pos=m['pos'], nrm=m['nrm'], uv=m['uv'], idx=m['idx'], **r)
a['base'] = webp(sys.argv[2] + '_base.jpg'); a['normal'] = webp(sys.argv[2] + '_normal.jpg')
dst = os.path.join(os.path.dirname(__file__), '..', '..', 'js', 'c3d_%s_mesh.js' % cfg['name'])
open(dst, 'w').write('// Generated by tools/glb (see tools/glb/README.md) from the modelled %s: simplified mesh, textures and auto-rig. Do not edit by hand.\nG.C3D_ASSETS = G.C3D_ASSETS || {};\nG.C3D_ASSETS[%d] = %s;\n' % (cfg['name'], cfg['id'], json.dumps(a, separators=(',', ':'))))
print(dst, os.path.getsize(dst), 'bytes')
