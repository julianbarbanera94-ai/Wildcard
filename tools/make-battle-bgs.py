# Builds js/battlebg.js: python3 tools/make-battle-bgs.py <folder with the 8 battle scene backgrounds (1536x640)>
# Each picture is cropped (centre) to the battle's 3:2 shape, saved as a 960x640 JPEG data URI.
import sys, base64, io, os
from PIL import Image
folder = sys.argv[1]
OUT = {}
def pack(im, size, q=80):
    b = io.BytesIO(); im.resize(size, Image.LANCZOS).save(b, 'JPEG', quality=q, optimize=True, progressive=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()
FILES = {'grass': '01_evergreen_meadow.png', 'forest': '02_forest_clearing.png', 'mountain': '03_mountain_pass.png', 'waterfall': '04_waterfall_basin.png', 'desert': '05_desert_canyon.png', 'volcano': '06_volcanic_arena.png', 'ruins': '07_moonlit_ruins.png', 'crystal': '08_crystal_cavern.png'}
for k, f in FILES.items():
    im = Image.open(os.path.join(folder, f)).convert('RGB'); w, h = im.size; cw = int(h * 1.5); x0 = (w - cw) // 2
    OUT[k] = pack(im.crop((x0, 0, x0 + cw, h)), (960, 640))
with open(os.path.join(os.path.dirname(__file__), '..', 'js', 'battlebg.js'), 'w') as fh:
    fh.write("// Painted battle arenas (docs/BATTLE_UI.md), generated by tools/make-battle-bgs.py from the supplied wildcard_battle_scene_backgrounds: each is cropped to\n// the battle's 3:2 and compressed. battle.js picks one by the map's biome. The creatures and the HUD are separate layers over them.\nglobalThis.G.battleBg = {\n")
    for k, v in OUT.items(): fh.write(f"  {k}: '{v}',\n")
    fh.write("};\n")
print({k: len(v) // 1024 for k, v in OUT.items()})
