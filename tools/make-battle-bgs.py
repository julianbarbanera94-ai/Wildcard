# Builds js/battlebg.js: python3 tools/make-battle-bgs.py <grass 1672x941 background.png> <folder with the 8 backgrounds>
# Each picture is cropped to the battle's 3:2 shape, upscaled smoothly to 720x480 and saved as a JPEG data URI.
import sys, base64, io, os
from PIL import Image, ImageFilter
grass_src, folder = sys.argv[1], sys.argv[2]
OUT = {}
def pack(im, size, q=82):
    im = im.resize(size, Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=1.2, percent=40, threshold=2))
    b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True, progressive=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()
g = Image.open(grass_src).convert('RGB'); W, H = g.size; cw = int(H * 1.5); x0 = int((W - cw) * .62)
OUT['grass'] = pack(g.crop((x0, 0, x0 + cw, H)), (960, 640), 80)
FILES = {'forest': '02_forest_grove.png', 'mountain': '03_mountain_pass.png', 'waterfall': '04_waterfall_basin.png', 'desert': '05_desert_canyon.png', 'volcano': '06_volcanic_fields.png', 'ruins': '07_night_ruins.png', 'crystal': '08_crystal_cavern.png'}
for k, f in FILES.items():
    im = Image.open(os.path.join(folder, f)).convert('RGB'); w, h = im.size; cw = int(h * 1.5); x0 = (w - cw) // 2
    OUT[k] = pack(im.crop((x0, 0, x0 + cw, h)), (720, 480))
with open(os.path.join(os.path.dirname(__file__), '..', 'js', 'battlebg.js'), 'w') as fh:
    fh.write("// Painted battle arenas (docs/BATTLE_UI.md), generated by tools/make-battle-bgs.py from the supplied backgrounds: each is cropped to\n// the battle's 3:2 and compressed. battle.js picks one by the map's biome. The creatures and the HUD are separate layers over them.\nglobalThis.G.battleBg = {\n")
    for k, v in OUT.items(): fh.write(f"  {k}: '{v}',\n")
    fh.write("};\n")
print({k: len(v) // 1024 for k, v in OUT.items()})
