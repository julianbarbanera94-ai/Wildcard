#!/usr/bin/env python3
"""Pack the people cut-outs in assets/people/ (<slug>-front|side|back.png) into js/peopleimg.js as embedded WebP (G.PEOPLE_IMG).
Slugs are matched to in-game looks in js/sprites.js (PEOPLE_ST / PEOPLE_LOOKS). Run after adding or changing people art:
  python3 tools/build-people-images.py"""
import base64, glob, io, os, re
from PIL import Image
root = os.path.join(os.path.dirname(__file__), '..')
out = {}
for f in sorted(glob.glob(os.path.join(root, 'assets/people/*-*.png'))):
    m = re.match(r'(.+)-(front|side|back)\.png$', os.path.basename(f))
    if not m: continue
    im = Image.open(f).convert('RGBA')
    if im.height > 320: im = im.resize((round(im.width * 320 / im.height), 320), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=88, method=6, alpha_quality=95)
    out.setdefault(m.group(1), {})[m.group(2)] = 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
lines = ['// Generated by tools/build-people-images.py from assets/people/*.png. Do not edit by hand.',
         '// Painted people: front, side (faces left) and back views, keyed by character (see js/sprites.js).', 'G.PEOPLE_IMG = {']
for k in sorted(out):
    v = out[k]
    if all(x in v for x in ('front', 'side', 'back')): lines.append(f"  '{k}': {{ " + ', '.join(f"{n}: '{v[n]}'" for n in ('front', 'side', 'back')) + ' },')
lines += ['};', '']
open(os.path.join(root, 'js/peopleimg.js'), 'w').write('\n'.join(lines))
print('people:', sorted(k for k in out if all(x in out[k] for x in ('front', 'side', 'back'))), os.path.getsize(os.path.join(root, 'js/peopleimg.js')), 'bytes')
