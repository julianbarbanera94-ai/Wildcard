#!/usr/bin/env python3
"""Pack the painted creature sprites in assets/creatures/ (NNN-front.png, NNN-back.png) into js/creatureimg.js as embedded
WebP data, so the game and the APK need no extra files and canvases are never tainted. Run after adding or changing art:
  python3 tools/build-creature-images.py
A species with a front image uses it instead of the generated art (js/sprites.js); the back image is optional (the front is
mirrored when it is missing)."""
import base64, glob, io, os, re
from PIL import Image
root = os.path.join(os.path.dirname(__file__), '..')
out = {}
for f in sorted(glob.glob(os.path.join(root, 'assets/creatures/*-*.png'))):
    m = re.match(r'(\d+)-(front|back)\.png$', os.path.basename(f))
    if not m: continue
    im = Image.open(f).convert('RGBA')
    if im.height > 360: im = im.resize((round(im.width * 360 / im.height), 360), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=90, method=6, alpha_quality=95)
    out.setdefault(int(m.group(1)), {})['f' if m.group(2) == 'front' else 'b'] = 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
lines = ['// Generated by tools/build-creature-images.py from assets/creatures/*.png. Do not edit by hand.',
         '// Painted sprites (front, and back for the player\'s side in battle) that replace the generated art for these species.',
         'G.CREATURE_IMG = {']
for k in sorted(out): lines.append(f"  {k}: {{ {', '.join(f'{v}: {chr(39)}{u}{chr(39)}' for v, u in sorted(out[k].items(), key=lambda t: t[0] != 'f'))} }},")
lines += ['};', '']
open(os.path.join(root, 'js/creatureimg.js'), 'w').write('\n'.join(lines))
print('species:', sorted(out), 'bytes:', os.path.getsize(os.path.join(root, 'js/creatureimg.js')))
